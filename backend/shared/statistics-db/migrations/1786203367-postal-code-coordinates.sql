-- Where each Belgian postal code is, so the reports can put a member count on a map.
--
-- Metabase cannot geocode: a pin map needs the coordinates as columns, and nothing in the member
-- administration holds them. They do not come from the sync either, because there is no upstream
-- table to sync from -- this is a fixed lookup of the country's postal codes, so it ships with the
-- migration rather than being loaded per environment.
--
-- One point per postal code, the centre of the area it covers. Where the source lists a postal code
-- once per sub-municipality (Brussels 1000 covers Brussel, Elsene and Sint-Joost-ten-Node), the
-- distinct points are averaged. A centre tells you no more about a member than the postal code the
-- report already groups on.
--
-- Source: Belgian postal codes with their geographic centre, published by bpost via Opendatasoft
-- (georef-belgium-postal-codes). `city` is the Dutch sub-municipality name, which that source only
-- gives for part of the country, so it is null for the rest. Nothing reads it; it is there to make
-- the table legible when checking why a point sits where it does.

