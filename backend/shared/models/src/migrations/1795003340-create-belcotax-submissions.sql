CREATE TABLE `belcotax_submissions` (
  `id` varchar(36) NOT NULL,
  `organizationId` varchar(36) NOT NULL,
  `templateId` varchar(36) NOT NULL,
  `companyNumber` varchar(10) NOT NULL,
  `userId` varchar(36) DEFAULT NULL,
  `submittedBy` varchar(255) NOT NULL,
  `status` varchar(36) NOT NULL,
  `bulkId` varchar(255) DEFAULT NULL,
  `ficheCount` int NOT NULL,
  `deletedCount` int NOT NULL,
  `content` json NOT NULL,
  `issues` json NOT NULL,
  `errorMessage` text,
  `lastPolledAt` datetime DEFAULT NULL,
  `finishedAt` datetime DEFAULT NULL,
  `createdAt` datetime NOT NULL,
  `updatedAt` datetime NOT NULL,
  PRIMARY KEY (`id`),
  KEY `templateId_createdAt` (`templateId`,`createdAt`),
  KEY `companyNumber_status` (`companyNumber`,`status`),
  KEY `status` (`status`),
  CONSTRAINT `belcotax_submissions_ibfk_1` FOREIGN KEY (`organizationId`) REFERENCES `organizations` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `belcotax_submissions_ibfk_2` FOREIGN KEY (`templateId`) REFERENCES `document_templates` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `belcotax_submissions_ibfk_3` FOREIGN KEY (`userId`) REFERENCES `users` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
