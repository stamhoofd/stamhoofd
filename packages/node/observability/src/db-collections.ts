export function isDevCollection(value: unknown): value is string {
    return typeof value === 'string' && collections.has(value);
}

export function isDevCollections(value: unknown): value is string[] {
    return (
        Array.isArray(value) &&
        value.length >= 2 &&
        value.length <= 4 &&
        value.every(isDevCollection) &&
        new Set(value).size === value.length
    );
}
